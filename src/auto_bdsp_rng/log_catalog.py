def application_copy(source: str, text: str) -> tuple[str, str]:
    """Select approved copy; never publish an unmatched diagnostic suffix."""
    if source not in SOURCES:
        return "", ""
    if text in _PUBLIC_NOTICES:
        return text.replace("系统级键盘捕获", "键盘控制"), ""
    if text in _NOTICES:
        return _NOTICES[text], ""
    for prefix, summary, action in _FAILURES:
        if text.startswith(prefix):
            if text.startswith("捕捉亮屏保活 CLI 未能及时停止"):
                return "亮屏保活尚未停止，已取消后续脚本启动", "请停止当前任务后重试。"
            return summary, action
    if source == "伊机控" and re.match(r"(?:serial\.serialutil\.)?SerialException:.*could not open port", text, re.IGNORECASE):
        return "伊机控串口无法打开", "请检查单片机连接和串口选择，关闭占用串口的其他程序后重试。"
    match = re.fullmatch(r"第 (\d+) 行参数 ([$\w]+) 需要填写", text)
    if match:
        return f"脚本第 {match[1]} 行缺少必填参数 {match[2]}", "请填写该参数后重新运行。"
    if text.startswith("请先连接伊机控，无法执行"):
        return "操作未执行，请先连接伊机控", ""
    if text.startswith("CLI 不可用，无法执行"):
        return "操作未执行，伊机控执行程序不可用", "请检查执行程序设置。"
    if text.startswith("请先选择串口，无法执行"):
        return "操作未执行，请先选择伊机控串口", ""
    if text.startswith("脚本已不存在，请重新选择"):
        return "所选脚本已不存在，请重新选择", ""
    if "自定义 ROI" in text and ("已回退" in text or "已使用默认范围" in text):
        return "自定义识别范围无效，已使用备用范围", "请检查当前画面与识别范围；本次识别继续进行。"
    match = re.fullmatch(r"错过目标；目标 Adv (\d+)；当前 Adv (\d+)", text)
    if match:
        return "已错过目标", f"目标推进 {int(match[1]):,}；当前推进 {int(match[2]):,}。"
    if text.startswith("本轮结果：错过目标"):
        return "本轮已错过目标", "请查看当前轮次的后续安排。"
    match = re.fullmatch(r"个性匹配失败，已忽略个性条件；反查完成；候选 (\d+) 个", text)
    if match:
        return f"反查完成，找到 {match[1]} 个候选", "个性条件未匹配，已忽略该条件；请核对候选结果。"
    return "", ""
